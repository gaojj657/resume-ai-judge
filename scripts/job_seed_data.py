def build_jobs():
    """每次返回独立数据，四项必须项80分、两项加分项20分。"""
    jobs = []
    for name, description, duties, source_title, source_url, must, bonus in ROLES:
        criteria = []
        for kind, items, weights in (("must", must, (25, 20, 20, 15)), ("bonus", bonus, (10, 10))):
            for (key, title, requirement), weight in zip(items, weights, strict=True):
                criteria.append({
                    "key": key, "type": kind, "name": title,
                    "requirement": requirement, "max_score": weight,
                    "scoring_rule": (
                        f"有明确证据完整满足要求得{weight}分；证据仅支持部分要求得1—{weight - 1}分，"
                        "说明满足与缺失部分；明确不满足得0分；简历未提供证据标记待核实并得0分。"
                        "课程、个人项目与实习中的可验证成果可作为证据，不凭关键词推断能力。"
                    ),
                })
        sections = [f"# {name}", "## 岗位职责", duties, "## 必须项（80分）"]
        for row in criteria:
            if row["type"] == "bonus" and "## 加分项（20分）" not in sections:
                sections.append("## 加分项（20分）")
            sections.append(f"- {row['name']}（{row['max_score']}分）：{row['requirement']}")
        sections.extend([
            "## 评分与人工判断",
            "总分100分。必须项明确不满足时列出编号缺口，仍允许人工判断是否推进；未提供的信息标记待核实。",
            "## 模板说明与来源",
            "依据公开JD改写为通用模板；权重、必须/加分划分为本工具自行设计。"
            "未沿用来源企业的薪资、地点、年限及学历门槛；需要时由招聘方补充。",
            f"参考：{source_title}\n{source_url}\n检索日期：{RESEARCH_DATE}",
        ])
        jobs.append({"name": name, "description": description, "jd": "\n\n".join(sections),
                     "status": "open", "criteria": criteria})
    return jobs
